function isLocale(value: string | null | undefined): value is Locale {
  return value === 'ja' || value === 'en'
}

function isExperienceMode(value: string | null | undefined): value is ExperienceMode {
  return value === 'simple' || value === 'advanced'
}

function readStorage(key: string) {
  if (typeof window === 'undefined') return null
  try {
    return window.localStorage.getItem(key)
  } catch {
    return null
  }
}

function browserLocale(): Locale {
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ja') ? 'ja' : 'en'
}

export function readUiPreferences(): UiPreferences {
  const params = typeof window === 'undefined' ? undefined : new URLSearchParams(window.location.search)
  const locale = isLocale(params?.get('lang'))
    ? params!.get('lang') as Locale
    : isLocale(readStorage(LOCALE_STORAGE_KEY))
      ? readStorage(LOCALE_STORAGE_KEY) as Locale
      : browserLocale()
  const mode = isExperienceMode(params?.get('mode'))
    ? params!.get('mode') as ExperienceMode
    : isExperienceMode(readStorage(EXPERIENCE_MODE_STORAGE_KEY))
      ? readStorage(EXPERIENCE_MODE_STORAGE_KEY) as ExperienceMode
      : 'simple'
  return { locale, mode }
}

function persistPreference(key: string, value: string) {
  if (typeof window === 'undefined') return
  try {
    window.localStorage.setItem(key, value)
  } catch {
    // A locked-down browser can still use the in-memory preference.
  }
}

function updateUrl(preferences: UiPreferences) {
  if (typeof window === 'undefined' || typeof window.history?.replaceState !== 'function') return
  const url = new URL(window.location.href)
  url.searchParams.set('lang', preferences.locale)
  url.searchParams.set('mode', preferences.mode)
  window.history.replaceState({}, '', url)
}

export function useUiPreferences() {
  const [preferences, setPreferences] = useState<UiPreferences>(() => readUiPreferences())

  useEffect(() => {
    const handlePopState = () => setPreferences(readUiPreferences())
    window.addEventListener('popstate', handlePopState)
    document.documentElement.lang = preferences.locale
    document.documentElement.dataset.experienceMode = preferences.mode
    return () => window.removeEventListener('popstate', handlePopState)
  }, [preferences])

  const setLocale = useCallback((locale: Locale) => {
    setPreferences((current) => {
      const next = { ...current, locale }
      persistPreference(LOCALE_STORAGE_KEY, locale)
      updateUrl(next)
      return next
    })
  }, [])

  const setMode = useCallback((mode: ExperienceMode) => {
    setPreferences((current) => {
      const next = { ...current, mode }
      persistPreference(EXPERIENCE_MODE_STORAGE_KEY, mode)
      updateUrl(next)
      return next
    })
  }, [])

  return { ...preferences, setLocale, setMode }
}

export function createTranslator(locale: Locale): Translator {
  return (key, values) => {
    let message = messages[locale][key] ?? messages.en[key] ?? key
    for (const [name, value] of Object.entries(values ?? {})) message = message.replaceAll(`{${name}}`, String(value))
    return message
  }
}

export function useTranslator(locale: Locale) {
  return useMemo(() => createTranslator(locale), [locale])
}

export function localeLabel(locale: Locale) {
  return locale === 'ja' ? '日本語' : 'English'
}
